const COMMIT = '807d6a3097687f092a1d13f8e745fc79214a2326';
const UPSTREAM_FILE = 'personal-extension/extension.js';
const clone = process.argv[2] ?? join(homedir(), 'dev/marinara-translation-tools-upstream');
const out = new URL('../src/vendor/tt-1.8.0/', import.meta.url).pathname;

const source = execFileSync('git', ['-C', clone, 'show', `${COMMIT}:${UPSTREAM_FILE}`], { encoding: 'utf8', maxBuffer: 64 << 20 });
const lines = source.split('\n');
const sha = (s) => createHash('sha256').update(s).digest('hex');

/** Slice from the line containing `from` (first match) up to, not including, the line containing `to`. */
function slice(id, from, to, back = 0) {
  const found = lines.findIndex((l) => l.includes(from));
  const start = found < 0 ? found : found - back;
  if (start < 0) throw new Error(`${id}: start anchor not found: ${from}`);
  if (lines.filter((l) => l.includes(from)).length > 1) {
    throw new Error(`${id}: start anchor is not unique: ${from}`);
  }
  let end = lines.findIndex((l, i) => i > found && l.includes(to));
  if (end < 0) throw new Error(`${id}: end anchor not found: ${to}`);
  while (end > start && lines[end - 1].trim() === '') end--;
  const text = lines.slice(start, end).join('\n');
  return { id, from, to, startLine: start + 1, endLine: end, sha256: sha(text), text };
}

const provenance = { upstream: 'https://github.com/tlsiddl/marinara-translation-tools', commit: COMMIT, file: UPSTREAM_FILE, version: '1.8.0', fileSha256: sha(source), slices: {} };

function emit(file, { imports = '', open = '', slices, close = '' }) {
  const parts = [];
  for (const s of slices) {
    provenance.slices[`${file}#${s.id}`] = { startLine: s.startLine, endLine: s.endLine, sha256: s.sha256 };
    parts.push(`// ==== BEGIN VERBATIM ${s.id} (upstream ${UPSTREAM_FILE}@807d6a3 L${s.startLine}-L${s.endLine}, sha256 ${s.sha256})\n${s.text}\n// ==== END VERBATIM ${s.id}`);
  }
  const header = `// GENERATED by scripts/vendor-tt-1.8.0.mjs. Do not edit.
// The VERBATIM blocks are copied byte for byte from tlsiddl/marinara-translation-tools 1.8.0
// (${COMMIT.slice(0, 7)}, ${UPSTREAM_FILE}); the code around them is the LV host adapter.
// Upstream is derived from minikkuen/Marinara-Translation-Tools. The upstream author granted permission
// to port it; see THIRD_PARTY_NOTICES.md.
// @ts-nocheck -- verbatim upstream JavaScript without type annotations.
/* eslint-disable */
`;
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, file), `${header}${imports}${open}${parts.join('\n\n')}\n${close}`);
}

